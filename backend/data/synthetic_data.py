def get_rainfall_trend():
    """Returns last-24-hour rainfall for chart rendering (mm/hr per hour)."""
    base_ahm = [8, 7, 9, 12, 15, 18, 22, 28, 35, 38, 40, 42,
                44, 41, 38, 35, 32, 30, 28, 32, 36, 40, 42, 45]
    base_srt = [10, 9, 12, 16, 20, 25, 30, 38, 44, 48, 50, 52,
                54, 51, 49, 46, 44, 42, 40, 45, 48, 52, 54, 56]
    hours = [f"{h:02d}:00" for h in range(0, 24)]
    return {
        "hours": hours,
        "ahmedabad": base_ahm,
        "surat": base_srt,
    }


# ─── DASHBOARD SUMMARY ────────────────────────────────────────────────────────

def get_dashboard_summary():
    """Returns high-level KPI counts for the dashboard home cards."""
    active_incidents = len([i for i in INCIDENTS if i["status"] != "Resolved"])
    critical_zones = len(
        [z for z in AHMEDABAD_ZONES + SURAT_ZONES if z["risk_level"] == "Critical"]
    )
    avg_rainfall = round(
        sum(z["rainfall_intensity"] for z in AHMEDABAD_ZONES + SURAT_ZONES) / 20, 1
    )
    critical_drains = len([d for d in DRAINS if d["condition"] == "Critical"])
    total_citizen_reports = sum(
        z["citizen_reports_count"] for z in AHMEDABAD_ZONES + SURAT_ZONES
    )
    return {
        "active_incidents": active_incidents,
        "high_risk_zones": critical_zones,
        "current_rainfall_mmhr": avg_rainfall,
        "critical_drains": critical_drains,
        "active_response_teams": 8,
        "citizen_reports": total_citizen_reports,
        "ahmedabad_risk": "High",
        "surat_risk": "Critical",
    }


def get_all_zones():
    return AHMEDABAD_ZONES + SURAT_ZONES


def get_zones_by_city(city: str):
    all_zones = get_all_zones()
    return [z for z in all_zones if z["city"].lower() == city.lower()]
